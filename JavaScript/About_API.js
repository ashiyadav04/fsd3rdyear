// Important terms

// 1. Client
// The application that sends the request.
// Example: a website built with JavaScript.

// 2. Server
// The system that processes the request and sends back a response.

// 3. Endpoint
// A specific URL through which an API can be accessed.


// 4. Request
// The information sent from the client to the server.

// 5. Response
// The information returned by the server.

// 6. JSON
// A common format used to exchange data between the client and server.


// HTTP methods
// Method	Purpose
// GET  ->	Retrieve data
// POST	->  Create/send new data
// PUT	-> Update existing data
// PATCH ->Partially update data
// DELETE ->Delete data


// HTTP status codes
// 200 → Request successful
// 201 → Data successfully created
// 400 → Bad request
// 401 → Unauthorized
// 403 → Forbidden
// 404 → Resource not found
// 500 → Server error








